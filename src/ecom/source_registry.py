def get_expected_source_files():
    """Return the list of source file names ingestion must find."""
    return list(SOURCE_FILE_SCHEMAS.keys())


def get_required_columns(file_name):
    """Return the required column names for one source file."""
    return SOURCE_FILE_SCHEMAS[file_name]
